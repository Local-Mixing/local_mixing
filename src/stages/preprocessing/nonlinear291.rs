//! Native adapter from heterogeneous GSS source gates to the canonical
//! `nonlinear291` E-encoding gadgets. The shared 193 topology is compiled only
//! for historical callers with `legacy-tools`.
//!
//! Each logical value is represented by two five-wire blocks with
//! `E(x) = x0 ^ x1 ^ maj(x2, x3, x4)`.  The public low wires are deliberately
//! kept separate from those carriers: the ingress derives balanced carrier
//! masks from a stable raw-data prefix and solves share-one lane zero so the
//! two blocks still decode to the raw logical bit.  The egress uses a clean
//! delta wire to replace the raw bit by the final two-share decode.
//! Consequently the returned circuit implements the source only on the
//! documented zero slice (every nondata input wire zero), exactly like the
//! other GSS gadgetizers.
//!
//! The per-operation gate bodies are compile-time canonical `mpmct1`
//! templates generated by the Python reference package.  The complete
//! `nonlinear291` adapter output, including its decomposed slice-zero preblock,
//! has physical fan-in at most two.  Later mixing stages have their own gate
//! vocabulary and are not covered by that statement.

